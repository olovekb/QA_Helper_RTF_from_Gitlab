/**
 * Краткая версия для вставки в любой промпт
 */
export const SHORT_NO_HALLUCINATIONS = `
🚨 НЕ ВЫДУМЫВАЙ! Генерируй ТОЛЬКО то, что ЯВНО описано в требованиях!
`;

/**
 * Добавляет правило "НЕ ВЫДУМЫВАЙ" к существующему промпту
 * @param {string} existingPrompt - Существующий промпт
 * @param {string} type - Тип: 'model', 'testcases', или 'short'
 * @returns {string} Промпт с добавленным правилом
 */
export function addNoHallucinationsRule(existingPrompt, type = 'short') {
    let rule;
    
    switch (type) {
        case 'model':
            rule = MODEL_NO_HALLUCINATIONS;
            break;
        case 'testcases':
            rule = TEST_CASES_NO_HALLUCINATIONS;
            break;
        case 'full':
            rule = NO_HALLUCINATIONS_RULE;
            break;
        case 'short':
        default:
            rule = SHORT_NO_HALLUCINATIONS;
    }
    
    // Добавляем в начало промпта
    return rule + '\n\n' + existingPrompt;
}

