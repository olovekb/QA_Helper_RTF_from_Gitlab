// analyzeRequirementWithAI.mjs

import fetch from 'node-fetch';
import fs from 'fs';

export async function analyzeRequirementWithAI(requirementText) {
  try {
    const prompt = `Ты эксперт по системному анализу и тестированию. Проанализируй следующее требование на соответствие критериям качества требований (по ISO/IEC/IEEE 29148 и практикам QA):

------------------------------------------------
${requirementText}
------------------------------------------------

Проверь требование по следующим критериям:

1. **Завершённость** — не упущены ли важные детали? Нет ли фраз типа \"и т.д.\", \"по возможности\", \"будет определено позже\"?
2. **Атомарность** — не содержит ли требование сразу несколько независимых условий или действий?
3. **Непротиворечивость** — нет ли внутренних конфликтов или логических несостыковок?
4. **Недвусмысленность** — можно ли однозначно интерпретировать содержание? Избегаются ли общие слова вроде \"удобно\", \"нормально\", \"эффективно\"?
5. **Выполнимость** — реально ли реализовать это требование технически?
6. **Проверяемость** — можно ли протестировать выполнение требования? Есть ли чёткий критерий?
7. **Обязательность** — ясно ли, является ли требование обязательным, опциональным или будущим?

Дай подробный анализ и конкретные рекомендации по улучшению. 
Плохие рекомендации:

«Насколько быстро?» (На это вы рискуете получить ответы в стиле «очень быстро», «максимально быстро», «нууу… просто быстро».)
«А если не получится быстро?» (Этим вы рискуете просто уйти в размышления или даже раздражить заказчика.)
«Всегда?» («Да, всегда. Хм, а вы ожидали другого ответа?»)

Хорошие рекомендации:

«Каково максимально допустимое время запуска приложения?»
«На каком оборудовании и при какой загрузочном сценарии нужно проверить запуск?»
«Допускается ли фоновая прогрузка или подгрузка модулей во время запуска?»
«Есть ли какие-то требования к кэшированию приложения при запуске?»
«Что происходит, если время запуска превышает установленный лимит и приложение так и не загрузилось?»

В конце нужен краткий формат "Требование (без номера) - рекомендация" списком`;

    const API_TOKEN = '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';
    const URL = 'https://openrouter.ai/api/v1/chat/completions';

    const headers = {
      "Authorization": `Bearer ${API_TOKEN}`,
      "HTTP-Referer": "<YOUR_SITE_URL>",
      "X-Title": "<YOUR_SITE_NAME>",
      "Content-Type": "application/json"
    };

    const body = JSON.stringify({
      model: "deepseek/deepseek-chat:free",
      messages: [
        {
          role: "user",
          content: prompt
        }
      ]
    });

    const response = await fetch(URL, {
      method: "POST",
      headers,
      body
    });

    const data = await response.json();

    if (data.error) {
      throw new Error(`Ошибка API: ${data.error.message || JSON.stringify(data.error)}`);
    }

    const content = data.choices?.[0]?.message?.content?.trim();
    if (!content) throw new Error('Ответ от модели пустой');

    const filename = 'requirement-analysis.txt';
    fs.writeFileSync(filename, content, 'utf8');
    console.log(`Результат анализа записан в файл: ${filename}`);

    return content;
  } catch (err) {
    console.error('Ошибка анализа требования:', err.message);
    throw err;
  }
}
